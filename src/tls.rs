//! TLS (pure-Rust rustls). OWNER: Subagent A.
//! domain mode: load --tls-cert/--tls-key. local mode: use them if given, otherwise generate (and persist under
//! `<data_dir>/tls/`) a local CA + server certificate with rcgen covering localhost, 127.0.0.1, ::1, --domain, the host name
//! and all LAN IPs. The CA (`local-ca.pem`) is what phones/browsers install; it is created once and never silently replaced.
use crate::config::Config;
use anyhow::Context;
use axum_server::tls_rustls::RustlsConfig;
use rcgen::{BasicConstraints, CertificateParams, DistinguishedName, DnType, ExtendedKeyUsagePurpose, IsCa, KeyPair, KeyUsagePurpose, SanType};
use serde::{Deserialize, Serialize};
use std::{
    collections::BTreeSet,
    fs,
    io::Write,
    net::IpAddr,
    path::{Path, PathBuf},
};
use time::{Duration, OffsetDateTime};

const CA_DAYS: i64 = 3650;
const SERVER_DAYS: i64 = 365; // browsers/Apple reject leaf certificates valid for more than 398 days
const RENEW_BEFORE_DAYS: i64 = 30;

pub async fn rustls_config(cfg: &Config) -> anyhow::Result<RustlsConfig> {
    match (&cfg.tls_cert, &cfg.tls_key) {
        (Some(c), Some(k)) => {
            warn_if_key_is_readable(k);
            Ok(RustlsConfig::from_pem_file(c, k).await.with_context(|| format!("loading TLS certificate {} / key {}", c.display(), k.display()))?)
        }
        _ => {
            let dir = cfg.data_dir.join("tls");
            let domain = cfg.domain.clone();
            let local = tokio::task::spawn_blocking(move || ensure_local_certs(&dir, domain.as_deref())).await??;
            tracing::info!("local CA certificate (install it on phones/browsers to trust this server): {}", local.ca_path.display());
            Ok(RustlsConfig::from_pem(local.server_cert_pem, local.server_key_pem).await?)
        }
    }
}

#[cfg(unix)]
fn warn_if_key_is_readable(p: &Path) {
    use std::os::unix::fs::PermissionsExt;
    if let Ok(m) = fs::metadata(p) {
        if m.permissions().mode() & 0o077 != 0 { tracing::warn!(path = %p.display(), "TLS private key is accessible by other users - chmod 600 it"); }
    }
}
#[cfg(not(unix))]
fn warn_if_key_is_readable(_: &Path) {}

pub struct LocalTls {
    pub ca_path: PathBuf,
    pub ca_pem: String,
    pub server_cert_pem: Vec<u8>,
    pub server_key_pem: Vec<u8>,
    /// True when the server certificate was (re)generated by this call.
    pub regenerated: bool,
    pub sans: Vec<String>,
}

#[derive(Serialize, Deserialize)]
struct Meta { ca_not_after: i64, server_not_after: i64, sans: Vec<String> }

fn ca_params() -> CertificateParams {
    let mut p = CertificateParams::default();
    let mut dn = DistinguishedName::new();
    dn.push(DnType::OrganizationName, "Water ERP");
    dn.push(DnType::CommonName, "Water ERP Local CA");
    p.distinguished_name = dn;
    p.is_ca = IsCa::Ca(BasicConstraints::Constrained(0));
    p.key_usages = vec![KeyUsagePurpose::KeyCertSign, KeyUsagePurpose::CrlSign];
    p
}

/// Write `data` to `path` atomically with owner-only permissions on unix (the key never exists with wider permissions).
fn write_private(path: &Path, data: &[u8]) -> anyhow::Result<()> {
    let tmp = path.with_extension("tmp");
    let _ = fs::remove_file(&tmp);
    let mut opts = fs::OpenOptions::new();
    opts.write(true).create_new(true);
    #[cfg(unix)]
    { use std::os::unix::fs::OpenOptionsExt; opts.mode(0o600); }
    let mut f = opts.open(&tmp).with_context(|| format!("creating {}", tmp.display()))?;
    f.write_all(data)?;
    f.sync_all()?;
    fs::rename(&tmp, path)?;
    Ok(())
}

fn host_name() -> Option<String> {
    let raw = fs::read_to_string("/etc/hostname").ok()
        .or_else(|| std::env::var("HOSTNAME").ok()).or_else(|| std::env::var("COMPUTERNAME").ok())?;
    let h = raw.trim().to_string();
    if valid_dns(&h) { Some(h) } else { None }
}

fn valid_dns(h: &str) -> bool {
    !h.is_empty() && h.len() <= 253 && h.is_ascii()
        && h.split('.').all(|l| !l.is_empty() && l.len() <= 63 && l.chars().all(|c| c.is_ascii_alphanumeric() || c == '-') && !l.starts_with('-') && !l.ends_with('-'))
}

/// Collect the names/IPs the server certificate must cover.
fn collect_sans(domain: Option<&str>) -> Vec<String> {
    let mut s: BTreeSet<String> = BTreeSet::new();
    s.insert("dns:localhost".into());
    s.insert("ip:127.0.0.1".into());
    s.insert("ip:::1".into());
    if let Some(d) = domain {
        let d = d.trim().trim_start_matches("https://").trim_start_matches("http://").trim_end_matches('/');
        let d = d.rsplit_once(':').filter(|(h, p)| !h.contains(':') && p.chars().all(|c| c.is_ascii_digit())).map_or(d, |(h, _)| h);
        if let Ok(ip) = d.trim_matches(|c| c == '[' || c == ']').parse::<IpAddr>() { s.insert(format!("ip:{ip}")); }
        else if valid_dns(d) { s.insert(format!("dns:{}", d.to_ascii_lowercase())); }
        else { tracing::warn!(domain = d, "--domain is not a valid host name; it is not added to the certificate"); }
    }
    if let Some(h) = host_name() { s.insert(format!("dns:{}", h.to_ascii_lowercase())); }
    if let Ok(ifs) = local_ip_address::list_afinet_netifas() {
        for (_, ip) in ifs {
            let skip = match ip { IpAddr::V4(v) => v.is_unspecified() || v.is_link_local() || v.is_multicast(), IpAddr::V6(v) => v.is_unspecified() || v.is_multicast() || (v.segments()[0] & 0xffc0) == 0xfe80 };
            if !skip { s.insert(format!("ip:{ip}")); }
        }
    }
    s.into_iter().collect()
}

fn to_san(entry: &str) -> anyhow::Result<SanType> {
    if let Some(ip) = entry.strip_prefix("ip:") { return Ok(SanType::IpAddress(ip.parse()?)); }
    let dns = entry.strip_prefix("dns:").context("bad SAN entry")?;
    Ok(SanType::DnsName(dns.to_string().try_into().map_err(|e| anyhow::anyhow!("bad DNS name {dns}: {e:?}"))?))
}

/// Create (or reuse) the local CA and server certificate under `dir`. See module docs.
pub fn ensure_local_certs(dir: &Path, domain: Option<&str>) -> anyhow::Result<LocalTls> {
    #[cfg(unix)]
    {
        use std::os::unix::fs::DirBuilderExt;
        fs::DirBuilder::new().recursive(true).mode(0o700).create(dir).with_context(|| format!("creating {}", dir.display()))?;
    }
    #[cfg(not(unix))]
    fs::create_dir_all(dir)?;
    let (ca_pem_path, ca_key_path) = (dir.join("local-ca.pem"), dir.join("local-ca.key"));
    let (srv_pem_path, srv_key_path, meta_path) = (dir.join("server.pem"), dir.join("server.key"), dir.join("server.meta.json"));
    let now = OffsetDateTime::now_utc();

    let mut meta: Option<Meta> = fs::read_to_string(&meta_path).ok().and_then(|s| serde_json::from_str(&s).ok());

    // --- CA: created once; only replaced when missing/unreadable or about to expire (phones must then reinstall it) ---
    let ca_exists = ca_pem_path.exists() && ca_key_path.exists();
    let ca_key: KeyPair;
    let mut ca_not_after = meta.as_ref().map_or(0, |m| m.ca_not_after);
    let ca_ok = ca_exists && fs::read_to_string(&ca_key_path).ok().and_then(|k| KeyPair::from_pem(&k).ok()).is_some()
        && ca_not_after > (now + Duration::days(RENEW_BEFORE_DAYS)).unix_timestamp();
    let ca_pem: String;
    if ca_ok {
        ca_key = KeyPair::from_pem(&fs::read_to_string(&ca_key_path)?)?;
        ca_pem = fs::read_to_string(&ca_pem_path)?;
    } else {
        if ca_exists { tracing::warn!("local CA is missing metadata, unreadable or expiring: generating a NEW one - re-install local-ca.pem on all devices"); }
        ca_key = KeyPair::generate()?;
        let mut p = ca_params();
        p.not_before = now - Duration::days(1);
        p.not_after = now + Duration::days(CA_DAYS);
        ca_not_after = p.not_after.unix_timestamp();
        let cert = p.self_signed(&ca_key)?;
        ca_pem = cert.pem();
        write_private(&ca_key_path, ca_key.serialize_pem().as_bytes())?;
        fs::write(&ca_pem_path, &ca_pem)?;
        meta = None; // everything issued by the old CA is invalid
    }

    // --- server certificate: reuse unless SANs changed or it expires within RENEW_BEFORE_DAYS ---
    let sans = collect_sans(domain);
    let reuse = srv_pem_path.exists() && srv_key_path.exists()
        && meta.as_ref().map_or(false, |m| m.sans == sans && m.server_not_after > (now + Duration::days(RENEW_BEFORE_DAYS)).unix_timestamp());
    if reuse {
        return Ok(LocalTls { ca_path: ca_pem_path, ca_pem, server_cert_pem: fs::read(&srv_pem_path)?, server_key_pem: fs::read(&srv_key_path)?, regenerated: false, sans });
    }
    // Rebuild the CA as an issuer from the persisted key: identical DN + constraints + key => same subject/authority key ids,
    // so the leaf chains to the CA pem that was installed on devices (rcgen cannot parse certificates without x509-parser).
    let mut issuer_params = ca_params();
    issuer_params.not_before = now - Duration::days(1);
    issuer_params.not_after = now + Duration::days(CA_DAYS);
    let issuer = issuer_params.self_signed(&ca_key)?;

    let mut p = CertificateParams::default();
    let mut dn = DistinguishedName::new();
    dn.push(DnType::OrganizationName, "Water ERP");
    dn.push(DnType::CommonName, "Water ERP server");
    p.distinguished_name = dn;
    p.is_ca = IsCa::ExplicitNoCa;
    p.key_usages = vec![KeyUsagePurpose::DigitalSignature];
    p.extended_key_usages = vec![ExtendedKeyUsagePurpose::ServerAuth];
    p.subject_alt_names = sans.iter().map(|s| to_san(s)).collect::<anyhow::Result<Vec<_>>>()?;
    p.not_before = now - Duration::days(1);
    p.not_after = now + Duration::days(SERVER_DAYS);
    let server_not_after = p.not_after.unix_timestamp();
    let srv_key = KeyPair::generate()?;
    let cert = p.signed_by(&srv_key, &issuer, &ca_key)?;
    let (cert_pem, key_pem) = (cert.pem(), srv_key.serialize_pem());
    write_private(&srv_key_path, key_pem.as_bytes())?;
    fs::write(&srv_pem_path, &cert_pem)?;
    fs::write(&meta_path, serde_json::to_vec_pretty(&Meta { ca_not_after, server_not_after, sans: sans.clone() })?)?;
    tracing::info!(sans = ?sans, "generated local server certificate (valid {SERVER_DAYS} days)");
    Ok(LocalTls { ca_path: ca_pem_path, ca_pem, server_cert_pem: cert_pem.into_bytes(), server_key_pem: key_pem.into_bytes(), regenerated: true, sans })
}
