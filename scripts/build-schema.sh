#!/usr/bin/env bash
# Concatenate all migrations into db/schema_full.sql - a single readable file to review the whole schema or to
# bootstrap a database by hand (psql -f). The server itself always uses ./migrations via sqlx (tracks applied versions).
set -euo pipefail
cd "$(dirname "$0")/.."
{
  echo "-- GENERATED by scripts/build-schema.sh from migrations/*.sql - do not edit"
  for f in migrations/*.sql; do echo; echo "-- ===== $f ====="; cat "$f"; done
} > db/schema_full.sql
echo "wrote db/schema_full.sql ($(wc -l < db/schema_full.sql) lines)"
